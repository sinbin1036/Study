package payroll;

/**
 * 주문(Order)이 현재 어떤 "상태"에 있는지를 나타내는 열거형(enum)입니다.
 *
 * <p>
 * 열거형(enum)이란 "미리 정해 둔 몇 가지 값 중 하나만 고를 수 있는 타입"입니다.
 * 신호등이 빨강·노랑·초록 중 하나만 될 수 있는 것처럼,
 * 주문 상태도 아래 세 가지 중 하나만 될 수 있습니다. 그 밖의 엉뚱한 값은 들어갈 수 없습니다.
 * </p>
 *
 * <p>
 * 상태가 바뀌는 규칙(상태 기계, state machine)은 음식 주문에 비유하면 이해하기 쉽습니다.
 * </p>
 * <pre>
 *   IN_PROGRESS(조리 중) ──완료(complete)──▶ COMPLETED(음식 전달 완료)
 *          │
 *          └─────────취소(cancel)──────▶ CANCELLED(주문 취소됨)
 * </pre>
 * <p>
 * 조리 중인 음식은 "완료"하거나 "취소"할 수 있지만,
 * 이미 손님에게 전달된 음식(COMPLETED)을 취소하거나,
 * 이미 취소된 주문(CANCELLED)을 완료할 수는 없습니다.
 * 이 규칙은 {@link OrderController}와 {@link OrderModelAssembler}에서 실제로 적용됩니다.
 * </p>
 */
enum Status {

	// 진행 중(조리 중): 새 주문이 만들어지면 이 상태로 시작합니다. 이 상태에서만 취소/완료가 가능합니다.
	// (각 줄 끝의 "//"는 코드 자동 정렬 도구가 줄을 한 줄로 합치지 않도록 넣어 둔 빈 주석입니다.)
	IN_PROGRESS, //
	// 완료됨: 주문 처리가 끝난 상태입니다. 더 이상 상태를 바꿀 수 없습니다.
	COMPLETED, //
	// 취소됨: 주문이 취소된 상태입니다. 더 이상 상태를 바꿀 수 없습니다.
	CANCELLED
}
